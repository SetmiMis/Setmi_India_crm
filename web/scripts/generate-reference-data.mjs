#!/usr/bin/env node
// Generates reference data for the new CRM from the legacy Apps Script source (single source of truth):
//   - supabase/seed/01_reference.sql      (india_states + pincode_geo)
//   - web/src/lib/geo/states.generated.ts (state aliases, ISO codes, zones, centroids)
// Usage: node web/scripts/generate-reference-data.mjs   (from repo root or web/)
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

// Pull a top-level `const NAME = {...};` object literal out of a legacy file and evaluate it in isolation.
function extractConst(source, name) {
  const start = source.indexOf(`const ${name} = `);
  if (start < 0) throw new Error(`${name} not found`);
  let i = source.indexOf('{', start);
  let depth = 0;
  let inStr = null;
  for (let j = i; j < source.length; j++) {
    const ch = source[j];
    if (inStr) {
      if (ch === '\\') { j++; continue; }
      if (ch === inStr) inStr = null;
      continue;
    }
    if (ch === "'" || ch === '"') { inStr = ch; continue; }
    if (ch === '{') depth++;
    if (ch === '}') { depth--; if (depth === 0) return vm.runInNewContext('(' + source.slice(i, j + 1) + ')'); }
  }
  throw new Error(`${name} not terminated`);
}

const code = read('src/Code.js');
const map = read('src/MapAnalytics.js');
const pin = read('src/PincodeGeo.js');

const ISO = extractConst(code, 'INDIA_STATE_ISO_');
const ZONE = extractConst(map, 'STATE_ZONE_');
const CENTROID = extractConst(map, 'STATE_CENTROID_');
const PIN = extractConst(pin, 'PINCODE_LATLNG_');

const states = new Map();
for (const [, [iso, name]] of Object.entries(ISO)) {
  if (!states.has(name)) states.set(name, { name, iso, zone: ZONE[name] ?? null, ll: CENTROID[name] ?? null });
}
const missingZone = [...states.values()].filter((s) => !s.zone).map((s) => s.name);
if (missingZone.length) throw new Error('States without a zone: ' + missingZone.join(', '));

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
let sql = '-- GENERATED by web/scripts/generate-reference-data.mjs from src/Code.js, src/MapAnalytics.js, src/PincodeGeo.js.\n';
sql += '-- Pincode centroids: GeoNames export/zip/IN.txt, CC-BY 4.0. Safe to re-run (upserts).\n\n';
sql += 'insert into public.india_states (name, iso, zone, lat, lng) values\n';
sql += [...states.values()]
  .map((s) => `  (${q(s.name)}, ${q(s.iso)}, ${q(s.zone)}, ${s.ll ? s.ll[0] : 'null'}, ${s.ll ? s.ll[1] : 'null'})`)
  .join(',\n');
sql += '\non conflict (name) do update set iso = excluded.iso, zone = excluded.zone, lat = excluded.lat, lng = excluded.lng;\n\n';

const pins = Object.entries(PIN).filter(([k, v]) => /^\d{6}$/.test(k) && Array.isArray(v) && v.length === 2);
for (let i = 0; i < pins.length; i += 1000) {
  sql += 'insert into public.pincode_geo (pincode, lat, lng) values\n';
  sql += pins.slice(i, i + 1000).map(([k, [la, ln]]) => `  ('${k}', ${la}, ${ln})`).join(',\n');
  sql += '\non conflict (pincode) do update set lat = excluded.lat, lng = excluded.lng;\n';
}
fs.mkdirSync(path.join(root, 'supabase', 'seed'), { recursive: true });
fs.writeFileSync(path.join(root, 'supabase', 'seed', '01_reference.sql'), sql);

let ts = '// GENERATED by web/scripts/generate-reference-data.mjs from the legacy Apps Script source. Do not edit.\n\n';
ts += 'export type Zone = "North" | "South" | "East" | "West" | "Central" | "Northeast" | "Islands";\n';
ts += 'export const STATE_ALIASES: Readonly<Record<string, readonly [iso: string, name: string]>> = ' +
  JSON.stringify(ISO, null, 0).replace(/\],/g, '],\n  ') + ' as const;\n\n';
ts += 'export const STATES: ReadonlyArray<{ name: string; iso: string; zone: Zone; lat: number | null; lng: number | null }> = ' +
  JSON.stringify([...states.values()].map((s) => ({ name: s.name, iso: s.iso, zone: s.zone, lat: s.ll ? s.ll[0] : null, lng: s.ll ? s.ll[1] : null })), null, 1) +
  ' as const;\n';
fs.mkdirSync(path.join(root, 'web', 'src', 'lib', 'geo'), { recursive: true });
fs.writeFileSync(path.join(root, 'web', 'src', 'lib', 'geo', 'states.generated.ts'), ts);

console.log(`states: ${states.size}, pincodes: ${pins.length}`);
